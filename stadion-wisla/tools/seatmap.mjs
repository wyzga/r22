// Builds the seat map used by stadion.html from the club's seating plan (data/seats.json and data/sectors.json,
// as published by stadium.wislakrakow.com). Every seat of the bowl keeps its sector, row and number; positions
// are the plan's x, y (x along the main stand, y towards stand E). Rows are stored as runs of evenly spaced
// seats numbered one after another: [row, first number, x, y, count, dx, dy]. Run: node tools/seatmap.mjs
// The result replaces the block between the SEATMAP markers in stadion.html.
import fs from 'node:fs';
import path from 'node:path';

const dir = path.join(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
const read = f => JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
const seats = read('data/seats.json').seats, sectors = read('data/sectors.json').sectors;
const nameOf = Object.fromEntries(sectors.map(s => [s.id, s.name]));

// which stand and tier of the model each sector of the plan belongs to (seats on level 0, the bowl)
const TIER = {};
for (const n of ['H11', 'Maxfliz VIP Gold', 'VIP Lounge', 'A11']) TIER[n] = ['A', 'lower'];
for (const n of ['H21', 'H22', 'H23', 'VIP Royal', 'A21', 'A22', 'A23']) TIER[n] = ['A', 'upper'];
for (let i = 1; i <= 6; i++) { TIER['E1' + i] = ['E', 'lower']; TIER['E2' + i] = ['E', 'upper']; }
for (let i = 1; i <= 5; i++) { TIER['G' + i] = ['G', 'single']; TIER['C' + i] = ['C', 'single']; }
for (const c of 'BDF') {
  for (const i of [1, 2]) TIER[c + '1' + i] = [c, 'lower'];
  for (const i of [1, 2, 3, 4]) TIER[c + '2' + i] = [c, 'upper'];
}

const bySector = {};
let skipped = 0;
for (const q of seats) {
  const n = nameOf[q.sectorId];
  if (q.level !== 0 || !TIER[n]) { skipped++; continue; }
  ((bySector[n] ||= {})[q.row] ||= []).push(q);
}

const out = {};
let total = 0;
for (const [n, rows] of Object.entries(bySector)) {
  const runs = [];
  for (const [row, list] of Object.entries(rows)) {
    list.sort((a, b) => +a.label - +b.label);
    total += list.length;
    let i = 0;
    while (i < list.length) {
      // extend the run while numbers step by one and the seats keep the same spacing (within 3 plan units)
      let j = i + 1;
      if (j < list.length && +list[j].label - +list[i].label === 1) {
        const dx = list[j].x - list[i].x, dy = list[j].y - list[i].y;
        while (j + 1 < list.length && +list[j + 1].label - +list[j].label === 1
          && Math.abs(list[j + 1].x - list[j].x - dx) <= 3 && Math.abs(list[j + 1].y - list[j].y - dy) <= 3) j++;
        j++;
      }
      const a = list[i], b = list[j - 1], k = j - i;
      const r2 = v => Math.round(v * 100) / 100;
      runs.push(+row, +a.label, a.x, a.y, k, k > 1 ? r2((b.x - a.x) / (k - 1)) : 0, k > 1 ? r2((b.y - a.y) / (k - 1)) : 0);
      i = j;
    }
  }
  out[n] = [...TIER[n], runs];
}

const json = JSON.stringify(out);
const file = path.join(dir, 'stadion.html');
let html = fs.readFileSync(file, 'utf8');
const begin = '// SEATMAP-BEGIN', end = '// SEATMAP-END';
const a = html.indexOf(begin), b = html.indexOf(end);
if (a < 0 || b < 0) throw new Error('SEATMAP markers not found in stadion.html');
const nl = html.includes('\r\n') ? '\r\n' : '\n';
html = html.slice(0, a) + begin + ' (generated by tools/seatmap.mjs from data/seats.json — do not edit)' + nl
  + `const SEATMAP = ${json};` + nl + html.slice(b);
fs.writeFileSync(file, html);
console.log(`${total} seats in ${Object.keys(out).length} sectors (${skipped} boxes, balconies and media places left out), ${Math.round(json.length / 1024)} KB`);
